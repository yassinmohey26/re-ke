export type TranslationKey = keyof typeof translations;

export function getAdminTranslation(key: TranslationKey, locale: AdminLocale): string {
  const entry = translations[key];
  if (locale in entry) return (entry as Record<string, string>)[locale];
  if ('en' in entry) return (entry as Record<string, string>)['en'];
  return (entry as Record<string, string>)['de'];
}
